// gen_encoding_table.go writes encoding_table.go: for every byte, the set of
// Encoding modes in which it is written as is, plus the hexChar bit. The
// reference rules below are those of net/url's shouldEscape, copied so that
// the table stays in sync with the standard library. Run with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
)

type encoding uint8

const (
	encodePath encoding = 1 << iota
	encodePathSegment
	encodeHost
	encodeZone
	encodeUserPassword
	encodeQueryComponent
	encodeFragment
	hexChar
)

var encNames = []struct {
	enc  encoding
	name string
}{
	{encodeFragment, "EncodeFragment"},
	{encodeQueryComponent, "EncodeQueryComponent"},
	{encodeUserPassword, "EncodeUserPassword"},
	{encodeZone, "EncodeZone"},
	{encodeHost, "EncodeHost"},
	{encodePathSegment, "EncodePathSegment"},
	{encodePath, "EncodePath"},
}

func main() {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by gen_encoding_table.go using 'go generate'; DO NOT EDIT.")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "package gourl")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "// table holds, for every byte, the modes in which the byte is written")
	fmt.Fprintln(&out, "// unescaped, and hexChar for hexadecimal digits.")
	fmt.Fprintln(&out, "var table = [256]Encoding{")
	for i := range 256 {
		c := byte(i)
		var val []byte
		if ishex(c) {
			val = append(val, "hexChar"...)
		}
		for _, e := range encNames {
			if !shouldEscape(c, e.enc) {
				if len(val) > 0 {
					val = append(val, '|')
				}
				val = append(val, e.name...)
			}
		}
		if len(val) > 0 {
			fmt.Fprintf(&out, "\t%s: %s,\n", strconv.QuoteRune(rune(c)), val)
		}
	}
	fmt.Fprintln(&out, "}")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal("format:", err)
	}
	if err := os.WriteFile("encoding_table.go", src, 0o644); err != nil {
		log.Fatal("write:", err)
	}
}

// shouldEscape is net/url's rule: whether c must be percent-encoded when it
// appears in the component selected by mode.
func shouldEscape(c byte, mode encoding) bool {
	// RFC 3986 §2.3 unreserved characters (alphanum).
	if 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || '0' <= c && c <= '9' {
		return false
	}

	if mode == encodeHost || mode == encodeZone {
		// §3.2.2 allows the sub-delims in reg-name; ":" is allowed because
		// the port is part of the host, "[" and "]" for IPv6 literals, and
		// "<", ">", "\"" because a host cannot use percent-encoding for
		// ASCII bytes, so escaping them would make the host unparsable.
		switch c {
		case '!', '$', '&', '\'', '(', ')', '*', '+', ',', ';', '=', ':', '[', ']', '<', '>', '"':
			return false
		}
	}

	switch c {
	case '-', '_', '.', '~': // §2.3 unreserved characters (mark)
		return false

	case '$', '&', '+', ',', '/', ':', ';', '=', '?', '@': // §2.2 reserved characters
		switch mode {
		case encodePath: // §3.3
			// The RFC allows : @ & = + $ but saves / ; , for assigning
			// meaning to individual segments; a whole path keeps them too.
			return c == '?'

		case encodePathSegment: // §3.3
			return c == '/' || c == ';' || c == ',' || c == '?'

		case encodeUserPassword: // §3.2.1
			// The RFC allows ; : & = + $ , in userinfo; ":" separates the
			// password, so it is escaped as well.
			return c == '@' || c == '/' || c == '?' || c == ':'

		case encodeQueryComponent: // §3.4
			return true

		case encodeFragment: // §4.1
			return false
		}
	}

	if mode == encodeFragment {
		// The sub-delims that net/url leaves unescaped in a fragment.
		switch c {
		case '!', '(', ')', '*':
			return false
		}
	}

	return true
}

func ishex(c byte) bool {
	return '0' <= c && c <= '9' || 'a' <= c && c <= 'f' || 'A' <= c && c <= 'F'
}
